-- D-059 baseline: today's schema (SQLite, after D-058) on PostgreSQL 17 + pgvector. Lift and shift: same tables,
-- columns and text formats (timestamps stay ISO-8601 TEXT with a trailing Z, JSON stays TEXT, booleans stay INTEGER);
-- Postgres-native types come in a later migration (P2). Generated from the SQLite DDL, reviewed by hand.

CREATE EXTENSION IF NOT EXISTS vector;

-- the exact text format SQLite produced with strftime('%Y-%m-%dT%H:%M:%fZ', 'now'), e.g. 2026-10-12T02:40:59.123Z
CREATE FUNCTION utc_now_text() RETURNS text LANGUAGE sql STABLE
    AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

-- append-only tables refuse UPDATE and DELETE (AGENTS rule 6)
CREATE FUNCTION forbid_change() RETURNS trigger LANGUAGE plpgsql
    AS $$ BEGIN RAISE EXCEPTION '% is append-only', TG_TABLE_NAME; END $$;

